import assert from "node:assert/strict";
import {chromium} from "playwright";
import {fileURLToPath,pathToFileURL} from "node:url";
import path from "node:path";
import fs from "node:fs";
const base=path.dirname(fileURLToPath(import.meta.url));
const out=path.resolve(base,"../reports/v032-comparacion");
fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1672,height:941},deviceScaleFactor:1});
const errors=[];page.on("pageerror",e=>errors.push(String(e)));
await page.goto(pathToFileURL(path.join(base,"comparacion_v032_preview.html")).href);
await page.locator(".gCmpRoot").waitFor();
assert.equal(await page.locator(".gCmpTab").count(),4);
assert.equal(await page.locator(".gCmpChannelRow").count(),8);
assert.equal(await page.locator("[data-cmp-side='a']").count(),2);
assert.equal(await page.locator("[data-cmp-side='b']").count(),2);
assert.equal(await page.locator(".gCmpSlot.is-empty").count(),16);
assert.equal(await page.locator(".gCmpHeroArt").count(),0);
assert.ok(await page.locator(".gCmpRoot").screenshot({path:path.join(out,"01-vitrinas-vacias-8-oras.png")}));
await page.locator("[data-cmp-side='a']").first().dragTo(page.locator("[data-cmp-drop='a']"));
await page.locator("[data-cmp-side='b']").nth(1).dragTo(page.locator("[data-cmp-drop='b']"));
assert.equal(await page.locator(".gCmpHeroArt").count(),2);
assert.equal(await page.locator(".gCmpChannelRow").count(),6);
const baseDiff=await page.locator("[data-cmp-channel='Base'] .gCmpDelta").innerText();
assert.match(baseDiff,/\+4,4/);
assert.match(await page.locator("[data-cmp-channel='Hielo'] .gCmpDelta").innerText(),/-2,5/);
await page.locator(".gCmpRoot").screenshot({path:path.join(out,"02-dos-espadas-reales-poster.png")});
await page.locator("[data-cmp-family='a']").selectOption("Escudos");
assert.equal(await page.locator(".gCmpHeroArt").count(),0);
assert.equal(await page.locator(".gCmpSlot.is-empty").count(),16);
await page.locator("[data-cmp-side='a']").first().click();
await page.locator("[data-cmp-side='b']").nth(1).click();
assert.equal(await page.locator(".gCmpHeroArt").count(),2);
assert.equal(await page.locator(".gCmpChannelRow").count(),2);
await page.locator(".gCmpRoot").screenshot({path:path.join(out,"03-escudos-filtro.png")});
assert.equal(errors.length,0,errors.join("\n"));
const files=await page.locator(".gCmpNav img, .gCmpORA").evaluateAll(nodes=>nodes.map(n=>({url:n.getAttribute("src"),ok:n.complete&&n.naturalWidth>0})));
assert.ok(files.every(f=>f.ok),"No se cargaron todos los PNG ORA: "+JSON.stringify(files));
const info={status:"PASS",viewport:[1672,941],tabs:4,empty_slots_per_side:10,ornament_files_verified:files.length,drag_drop:true,family_filter:true,images_valid:true,js_errors:errors};
fs.writeFileSync(path.join(out,"diagnostico.json"),JSON.stringify(info,null,2));
await browser.close();
console.log(JSON.stringify(info));
